#!/usr/bin/env python3
"""Generate Mermaid from logical schema/contract; --check detects drift."""
import hashlib,json,sys
from pathlib import Path
root=Path(__file__).resolve().parents[1]
schema=json.loads((root/'contracts/schema.json').read_text())
api=json.loads((root/'contracts/openapi.json').read_text())
out=root/'docs/diagrams'
def header(title,source):
    h=hashlib.sha256((root/source).read_bytes()).hexdigest()
    return f'# {title}\n\nSource `{source}`; SHA-256 `{h}`. Generated by scripts/generate_diagrams.py.\n\n'
def diagram(title,source,lines): return header(title,source)+'```mermaid\n'+'\n'.join(lines)+'\n```\n'
erd=['erDiagram']
for name,table in schema['tables'].items():
    erd.append(f'  {name} {{')
    for field,info in table['fields'].items():
        marker=' PK' if field in table['primary_key'] else ' FK' if 'references' in info else ''
        erd.append(f'    {info["type"].replace("_","")} {field}{marker}')
    erd.append('  }')
for name,table in schema['tables'].items():
    for field,info in table['fields'].items():
        if 'references' in info:
            parent=info['references'].split('.')[0]
            card='|o' if info['nullable'] else '||'
            erd.append(f'  {parent} {card}--o{{ {name} : "{field}"')
files={'erd.md':diagram('Model data TERNAVA','contracts/schema.json',erd)}
actors=['sequenceDiagram','  participant U as Operator/pengelola','  participant L as Local repository','  participant A as Laravel API','  participant D as PostgreSQL','  participant W as Worker/FCM']
senders={'createDaily':[('U','L'),('L','A'),('A','A'),('A','D'),('D','D'),('A','L'),('L','L')],
 'reviseDaily':[('U','L'),('U','L'),('L','A'),('A','D'),('D','D'),('D','D'),('A','L')],
 'pullChanges':[('L','A'),('A','L'),('L','L'),('L','L')]}
for operation,steps in api['x-critical-sequences'].items():
    parts=actors.copy()+[f'  Note over L,A: operationId {operation}']
    assert len(steps)==len(senders[operation])
    for (sender,recipient),step in zip(senders[operation],steps): parts.append(f'  {sender}->>{recipient}: {step}')
    if operation!='pullChanges':
        parts+=['  opt Event committed','    D-->>W: durable event','    W->>D: dedup inbox(event,user)','    W-->>U: optional generic push','  end',
         '  alt ACK lost / timeout','    L->>A: same key and body','    A-->>L: original ACK after policy check','  else Version / stock / access failure','    A-->>L: typed error, no partial effect','    L-->>U: preserve item, review / reauth','  end']
    files['sequence-'+operation+'.md']=diagram(operation,'contracts/openapi.json',parts)
layers=api['x-layers'];arch=['flowchart LR','  subgraph Android']
for i in range(3): arch.append(f'    L{i}["{layers[i]}"]')
arch+=['    K["Platform secure storage"]','    K --- L1','  end','  subgraph Docker_local']
for i in range(3,7): arch.append(f'    L{i}["{layers[i]}"]')
arch+=['    S["Scheduler"]','    S --> L5','  end','  P["FCM optional"]','  B["Encrypted backup outside runtime host before pilot"]',
 '  L0 --> L1','  L1 --> L2','  L2 -->|REST bearer| L3','  L3 --> L4','  L4 --> L5','  L5 --> L6','  L6 --> P','  L5 --> B']
files['architecture.md']=diagram('Arsitektur','contracts/openapi.json',arch)
flow_source=root/'contracts/flows.json'
if not flow_source.exists():
    flow_source.write_text(json.dumps({
      'F-03':{'file':'daily-flow.md','acs':['AC-13','AC-23','AC-26','AC-27'],'mermaid':['flowchart TD',
       '  A[Hari ini: kandang ditugaskan] --> B[Isi total harian]','  B --> C{Lengkap?}',
       '  C -->|Belum| D[Draft lokal]','  D --> B','  C -->|Ya| E{Local commit berhasil?}',
       '  E -->|Gagal| F[Form tetap ada]','  F --> B','  E -->|Ya| G[Pending immutable dan key]',
       '  G --> H{Online dan sesi valid?}','  H -->|Belum| G','  H -->|Ya| I{Server commit?}',
       '  I -->|ACK| J[Diterima sistem]','  I -->|Timeout| G','  I -->|401/403| K[Reauth; antrean terkunci]',
       '  I -->|409/422| L[Review tanpa overwrite]','  L --> B']},
      'F-06':{'file':'incident-flow.md','acs':['AC-19','AC-20','AC-37'],'mermaid':['flowchart TD',
       '  A[Pengamatan manual] --> B[Local persist teks dan foto]','  B --> C[Sync teks]',
       '  C --> D{Hasil server}','  D -->|Ditolak / timeout| E[Preserve dan review / retry]',
       '  E --> C','  D -->|ACK| F[Temuan accepted]','  F --> G[Upload foto setelah ACK]',
       '  G --> H{Foto diterima?}','  H -->|Belum| I[Foto pending; teks accepted]','  I --> G',
       '  F --> J[Pengelola assign petugas]','  J --> K[Tindakan dengan versi]',
       '  K --> L{Penutupan dengan notes?}','  L -->|Belum| K','  L -->|Ya| M[Closed dan histori]']}}
       ,indent=2))
for name,entry in json.loads(flow_source.read_text()).items(): files[entry['file']]=diagram(name,'contracts/flows.json',entry['mermaid'])
files['README.md']='# Diagram TERNAVA\n\nGenerated; belum bukti implementasi.\n\n'+''.join(f'- [{x}]({x})\n' for x in files)+'\nPerbarui sumber dan diagram dalam perubahan yang sama. Check: `python3 scripts/generate_diagrams.py --check`.\n'
out.mkdir(parents=True,exist_ok=True)
if '--check' in sys.argv:
    drift=[f for f,v in files.items() if not (out/f).exists() or (out/f).read_text()!=v]
    if drift: raise SystemExit('Diagram drift: '+', '.join(drift))
    print(f'Diagrams consistent: {len(files)}')
else:
    for name,value in files.items(): (out/name).write_text(value)
    print(f'Generated {len(files)} diagram documents')
